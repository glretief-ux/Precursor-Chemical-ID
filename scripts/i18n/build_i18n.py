#!/usr/bin/env python3
"""Assemble docs/data/i18n-<lang>.js (the French, Spanish and Russian dictionaries for the site) from the sources in
this folder. Run by scripts/build.py. English text is the key, so adding a language never touches the data files.
Per language <l> the sources are: <l>_chem.py, <l>_exact.py, <l>_countries.py, <l>_rules.js, country_names_<l>.json and
the page text (fr_static.json for French; <l>/static_*.tsv for the others - numbered lines in the order of fr_static.json)."""
import importlib, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
LANGS = ("fr", "es", "ru")
KOSOVO = {"fr": "Kosovo", "es": "Kosovo", "ru": "Косово"}

def uniq(rows, field):
    seen = []
    for c in rows:
        v = c.get(field)
        for x in (v if isinstance(v, list) else [v]):
            if x and x not in seen:
                seen.append(x)
    return seen

def load_static(lang):
    keys = list(json.load(open(os.path.join(HERE, "fr_static.json"), encoding="utf-8")))
    if lang == "fr":
        static = json.load(open(os.path.join(HERE, "fr_static.json"), encoding="utf-8"))
    else:
        vals = {}
        d = os.path.join(HERE, lang)
        for fn in sorted(os.listdir(d)):
            if not fn.endswith(".tsv"):
                continue
            for line in open(os.path.join(d, fn), encoding="utf-8").read().split("\n"):
                if not line.strip():
                    continue
                i, _, v = line.partition("\t")
                vals[int(i)] = v
        missing = [i for i in range(len(keys)) if i not in vals]
        if missing or len(vals) != len(keys):
            sys.exit("i18n[%s]: page text has %d lines for %d strings (missing %s) - update scripts/i18n/%s/static_*.tsv" % (lang, len(vals), len(keys), missing[:8], lang))
        static = {k: vals[i] for i, k in enumerate(keys)}
    return {k: (v[1:] if k.startswith("@") and v.startswith("@") else v) for k, v in static.items()}

def build(lang):
    chem = importlib.import_module(lang + "_chem")
    ex = importlib.import_module(lang + "_exact")
    cc = importlib.import_module(lang + "_countries")
    chems = json.load(open(os.path.join(ROOT, "data", "chemicals.json"), encoding="utf-8"))
    chems = chems if isinstance(chems, list) else chems.get("chemicals", chems)
    countries = json.load(open(os.path.join(ROOT, "data", "countries.json"), encoding="utf-8"))
    static = load_static(lang)
    exact = dict(ex.EXACT)
    exact.update(ex.SUBREGIONS)
    pairs = [("category", chem.CAT), ("role", chem.ROLE), ("legit", chem.LEGIT), ("appearance", chem.APP), ("notes", chem.NOTES)]
    for field, tr in pairs:
        en = uniq(chems, field)
        if len(en) != len(tr):
            sys.exit("i18n[%s]: %s has %d unique English values but %d translations - update scripts/i18n/%s_chem.py" % (lang, field, len(en), len(tr), lang))
        exact.update(zip(en, tr))
    for d in uniq(chems, "drugs"):
        if d not in chem.DRUGS:
            sys.exit("i18n[%s]: missing drug name: %s" % (lang, d))
        exact[d] = chem.DRUGS[d]
    # country-level prose
    def cu(field, sub=None):
        out = []
        for c in countries["countries"].values():
            if sub is None:
                v = c.get(field)
                if v and v not in out: out.append(v)
            else:
                for e in c.get(field, []):
                    v = e.get(sub)
                    if v and v not in out: out.append(v)
        return out
    for en_list, tr_list, name in ((cu("basis"), cc.BASIS, "basis"), (cu("notes"), cc.NOTES, "notes"), (cu("extras", "note"), cc.XNOTE, "extras notes")):
        if len(en_list) != len(tr_list):
            sys.exit("i18n[%s]: country %s: %d English vs %d translated - update scripts/i18n/%s_countries.py" % (lang, name, len(en_list), len(tr_list), lang))
        exact.update(zip(en_list, tr_list))
    for g in cu("extras", "g"):
        if g not in exact:
            print("i18n[%s]: note - no translation for country group label: %s" % (lang, g), file=sys.stderr)
    names = json.load(open(os.path.join(HERE, "country_names_%s.json" % lang), encoding="utf-8"))
    names["XKX"] = KOSOVO[lang]
    rules = open(os.path.join(HERE, "%s_rules.js" % lang), encoding="utf-8").read().strip()
    return ("/* %s dictionary - generated by scripts/i18n/build_i18n.py, do not edit by hand. */\n"
            "window.I18N=window.I18N||{};window.I18N.%s={static:%s,exact:%s,country:%s,subregion:%s,rules:%s};\n") % (
        lang.upper(), lang,
        json.dumps(static, ensure_ascii=False, separators=(",", ":")),
        json.dumps(exact, ensure_ascii=False, separators=(",", ":")),
        json.dumps(names, ensure_ascii=False, separators=(",", ":")),
        json.dumps(ex.SUBREGIONS, ensure_ascii=False, separators=(",", ":")),
        rules)

def build_all():
    return {l: build(l) for l in LANGS}

if __name__ == "__main__":
    bad = 0
    for l, js in build_all().items():
        out = os.path.join(ROOT, "docs", "data", "i18n-%s.js" % l)
        old = open(out, encoding="utf-8").read() if os.path.exists(out) else None
        if "--check" in sys.argv:
            if old != js:
                print("docs/data/i18n-%s.js is out of date - run scripts/i18n/build_i18n.py" % l); bad = 1
            continue
        open(out, "w", encoding="utf-8").write(js)
        print("wrote", out, len(js))
    sys.exit(bad)
