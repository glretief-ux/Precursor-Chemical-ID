#!/usr/bin/env python3
"""Assemble docs/data/i18n-fr.js (French dictionary for the site) from the sources in this folder.
Run by scripts/build.py. English text is the key, so adding a language never touches the data files."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
from fr_chem import CAT, DRUGS, ROLE, LEGIT, APP, NOTES
from fr_countries import BASIS, NOTES as CNOTES, XNOTE
from fr_exact import EXACT, SUBREGIONS

def uniq(rows, field):
    seen = []
    for c in rows:
        v = c.get(field)
        for x in (v if isinstance(v, list) else [v]):
            if x and x not in seen:
                seen.append(x)
    return seen

def build():
    chems = json.load(open(os.path.join(ROOT, "data", "chemicals.json"), encoding="utf-8"))
    chems = chems if isinstance(chems, list) else chems.get("chemicals", chems)
    countries = json.load(open(os.path.join(ROOT, "data", "countries.json"), encoding="utf-8"))
    static = json.load(open(os.path.join(HERE, "fr_static.json"), encoding="utf-8"))
    static = {k: (v[1:] if k.startswith("@") and v.startswith("@") else v) for k, v in static.items()}
    exact = dict(EXACT)
    pairs = [("category", CAT), ("role", ROLE), ("legit", LEGIT), ("appearance", APP), ("notes", NOTES)]
    for field, fr in pairs:
        en = uniq(chems, field)
        if len(en) != len(fr):
            sys.exit("i18n: %s has %d unique English values but %d French ones - update scripts/i18n/fr_chem.py" % (field, len(en), len(fr)))
        exact.update(zip(en, fr))
    for d in uniq(chems, "drugs"):
        if d not in DRUGS:
            sys.exit("i18n: missing French drug name: " + d)
        exact[d] = DRUGS[d]
    # country-level prose
    def cu(field, sub=None):
        out = []
        for c in countries["countries"].values():
            if sub is None:
                v = c.get(field)
                if v and v not in out: out.append(v)
            else:
                for e in c.get(field, []):
                    v = e.get(sub)
                    if v and v not in out: out.append(v)
        return out
    for en_list, fr_list, name in ((cu("basis"), BASIS, "basis"), (cu("notes"), CNOTES, "notes"), (cu("extras", "note"), XNOTE, "extras notes")):
        if len(en_list) != len(fr_list):
            sys.exit("i18n: country %s: %d English vs %d French - update scripts/i18n/fr_countries.py" % (name, len(en_list), len(fr_list)))
        exact.update(zip(en_list, fr_list))
    for g in cu("extras", "g"):
        if g not in exact:
            print("i18n: note - no French for country group label:", g, file=sys.stderr)
    names = json.load(open(os.path.join(HERE, "country_names_fr.json"), encoding="utf-8"))
    names["XKX"] = "Kosovo"
    rules = open(os.path.join(HERE, "fr_rules.js"), encoding="utf-8").read().strip()
    js = ("/* French dictionary - generated by scripts/i18n/build_fr.py, do not edit by hand. */\n"
          "window.I18N_FR={static:%s,exact:%s,country:%s,subregion:%s,rules:%s};\n") % (
        json.dumps(static, ensure_ascii=False, separators=(",", ":")),
        json.dumps(exact, ensure_ascii=False, separators=(",", ":")),
        json.dumps(names, ensure_ascii=False, separators=(",", ":")),
        json.dumps(SUBREGIONS, ensure_ascii=False, separators=(",", ":")),
        rules)
    return js

if __name__ == "__main__":
    out = os.path.join(ROOT, "docs", "data", "i18n-fr.js")
    js = build()
    old = open(out, encoding="utf-8").read() if os.path.exists(out) else None
    if "--check" in sys.argv:
        sys.exit(0 if old == js else "docs/data/i18n-fr.js is out of date - run scripts/i18n/build_fr.py")
    open(out, "w", encoding="utf-8").write(js)
    print("wrote", out, len(js))
